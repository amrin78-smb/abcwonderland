using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using ABCWonderworld.Content;
using UnityEditor;
using UnityEngine;

namespace ABCWonderworld.EditorTools
{
    /// <summary>Writes the visible content-completeness register (GDD §11) from the validator results.</summary>
    public static class ContentReport
    {
        public const string OutPath = "../Documentation/CONTENT_COMPLETENESS.md";

        [MenuItem(ProjectSetup.MenuRoot + "Validate Content && Write Report", priority = 10)]
        public static void Menu()
        {
            var issues = ContentValidator.Validate(ContentCatalog.Load());
            Write(issues);
            Debug.Log($"[Validate] {issues.Count(i => i.Severity == IssueSeverity.Error)} errors, {issues.Count(i => i.Severity == IssueSeverity.Warning)} warnings. Report: {OutPath}");
        }

        public static void Write(List<ContentIssue> issues)
        {
            ContentCatalog c = ContentCatalog.Load();
            var sb = new StringBuilder();
            sb.AppendLine("# Content Completeness Register");
            sb.AppendLine();
            sb.AppendLine("Generated by `ABC Wonderworld > Validate Content` / `Tools/setup.sh`. Do not edit by hand.");
            sb.AppendLine("A content item is **not production-complete** while it is a placeholder, provisional, missing or pending review (GDD §11).");
            sb.AppendLine();
            sb.AppendLine($"Errors: **{issues.Count(i => i.Severity == IssueSeverity.Error)}**, warnings: **{issues.Count(i => i.Severity == IssueSeverity.Warning)}**");
            sb.AppendLine();
            if (c != null)
            {
                sb.AppendLine("| Letter | Character (art) | Vocabulary (art) | Tracing U/L | Voice name/sound/intro | Adventure | Phonics review |");
                sb.AppendLine("|---|---|---|---|---|---|---|");
                foreach (LetterDefinition l in c.letters)
                {
                    CharacterDefinition ch = c.CharacterFor(l);
                    string vocab = string.Join(", ", l.vocabulary.Select(v => v.word + (v.startsWithBeginnerSound ? "" : "†") + (string.IsNullOrEmpty(v.artNote) ? "" : "‡")));
                    string Voice(string k) { var e = c.audio?.Find(k); return e == null || e.clip == null ? "missing" : e.status.ToString().ToLowerInvariant(); }
                    sb.AppendLine($"| {l.upper}{l.lower} | {ch?.displayName} ({ch?.artStatus}) | {vocab} (placeholder) | {l.upperTracing?.status}/{l.lowerTracing?.status} | " +
                                  $"{Voice(l.nameAudioKey)}/{Voice(l.phonemeAudioKey)}/{Voice(l.introAudioKey)} | {l.adventure?.title} ({l.adventure?.archetype}{(l.adventure != null && System.Array.IndexOf(ABCWonderworld.Activities.AdventureActivity.Implemented, l.adventure.archetype) < 0 ? $" — PENDING, runs {ABCWonderworld.Activities.AdventureActivity.Effective(l.adventure.archetype)}" : "")}) | {l.reviewStatus} |");
                }
                sb.AppendLine();
                sb.AppendLine("† word contains the letter but does not start with the beginner sound (never used for initial-sound activities).  ");
                sb.AppendLine("‡ picture has an art note (see below).");
                sb.AppendLine();
            }
            sb.AppendLine("## Issues");
            sb.AppendLine();
            foreach (var g in issues.GroupBy(i => i.Severity).OrderByDescending(g => g.Key))
            {
                sb.AppendLine($"### {g.Key} ({g.Count()})");
                sb.AppendLine();
                foreach (ContentIssue i in g.Take(400)) sb.AppendLine($"- `{i.Subject}`: {i.Message}");
                sb.AppendLine();
            }
            File.WriteAllText(Path.GetFullPath(OutPath), sb.ToString());
        }
    }
}
